function methods = QuasiOpticalMethodCatalog
%QUASIOPTICALMETHODCATALOG Free-space slab conversion methods and tradeoffs.
% Qualitative speed/accuracy labels summarize the supplied Rohde & Schwarz
% application note, Tables 3/4, pp.11/16. They are comparison labels, not
% measured software performance, uncertainty bounds, or accuracy guarantees.
% All entries require calibrated complex slab reflection AND transmission,
% known thickness and the homogeneous isotropic model. NRW supports one
% fixed normal/oblique incidence and TE or TM; the other methods are normal-only.
% SCL is intentionally absent: the source uses a short-circuited guided fixture.

base = struct('id','','name','','channels','','outputs','','muTreatment','', ...
    'speed','','accuracyQualitative','','material','','advantages',{{}}, ...
    'disadvantages',{{}},'sourcePages',[],'setup','Free space', ...
    'assumptions',{{'Calibrated complex sample S11 and S21 at slab surfaces', ...
    'Known thickness; normal incidence; air on both sides', ...
    'Homogeneous isotropic slab; adequate plane-wave illumination'}}, ...
    'accuracyMeaning','Qualitative source comparison; actual uncertainty depends on calibration, sample and model', ...
    'status','Implemented for free-space normal-incidence scalar retrieval');
methods = repmat(base,1,3);

methods(1).id = 'NRW';
methods(1).name = 'NRW';
methods(1).channels = 'Complex S11 and S21; source also permits S11, S21, S12, S22';
methods(1).outputs = 'Complex scalar epsilon_r and mu_r';
methods(1).muTreatment = 'Retrieved independently with epsilon_r under isotropic assumptions';
methods(1).speed = 'Fast';
methods(1).accuracyQualitative = 'Medium';
methods(1).material = 'Large, flat solids; source free-space comparison lists nonmagnetic high-temperature samples';
methods(1).advantages = { ...
    'Direct, non-iterative calculation.', ...
    'Retrieves both scalar permittivity and permeability.', ...
    'Useful when magnetic response cannot be assumed absent.'};
methods(1).disadvantages = { ...
    'Poor conditioning near low-loss half-wave slab resonances.', ...
    'Logarithmic phase branch requires independent justification.', ...
    'Very weak transmission, calibration errors and thickness errors limit retrieval.'};
methods(1).sourcePages = [11 12 16 19 20 21];
methods(1).assumptions = {'Calibrated complex sample S11 and S21 at slab surfaces', ...
    'Known normal thickness; fixed incidence; explicit TE or TM; air on both sides', ...
    'Homogeneous isotropic slab; adequate plane-wave illumination'};
methods(1).status = 'Implemented for normal or oblique free-space TE/TM scalar retrieval';

methods(2).id = 'NIST iterative';
methods(2).name = 'NIST iterative';
methods(2).channels = 'Complex S11 and S21; source also permits S11, S21, S12, S22';
methods(2).outputs = 'Complex scalar epsilon_r; mu_r fixed to 1';
methods(2).muTreatment = 'Assumed mu_r = 1, not measured';
methods(2).speed = 'Slow';
methods(2).accuracyQualitative = 'Good';
methods(2).material = 'Large, flat nonmagnetic solids; source includes high-temperature samples';
methods(2).advantages = { ...
    'Fixing permeability reduces the inverse problem to permittivity.', ...
    'Avoids the independent NRW impedance division at half-wave resonances.', ...
    'Can support low-loss and longer samples with a suitable initial estimate.'};
methods(2).disadvantages = { ...
    'Requires a physically justified nonmagnetic assumption.', ...
    'Needs an initial permittivity guess and iterative convergence.', ...
    'May converge to a different branch or fail; a small residual alone is insufficient.'};
methods(2).sourcePages = [11 13 16 24 25 26];

methods(3).id = 'New non-iterative';
methods(3).name = 'New non-iterative';
methods(3).channels = 'Complex S11 and S21; source also permits S11, S21, S12, S22';
methods(3).outputs = 'Complex scalar epsilon_r; mu_r fixed to 1';
methods(3).muTreatment = 'Assumed mu_r = 1, not measured';
methods(3).speed = 'Fast';
methods(3).accuracyQualitative = 'Good';
methods(3).material = 'Large, flat nonmagnetic solids; source includes high-temperature samples';
methods(3).advantages = { ...
    'Direct propagation-based permittivity calculation.', ...
    'No iterative initial permittivity guess is required.', ...
    'Avoids dividing the propagation index by independently retrieved impedance.'};
methods(3).disadvantages = { ...
    'Requires a physically justified nonmagnetic assumption.', ...
    'Propagation phase still has logarithmic branch ambiguity.', ...
    'Interface-root extraction, weak transmission and model mismatch can remain ill-conditioned.'};
methods(3).sourcePages = [11 14 16 27 28];
end
