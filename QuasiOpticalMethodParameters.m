function params = QuasiOpticalMethodParameters
%QUASIOPTICALMETHODPARAMETERS Metadata for exported free-space method tables.
% Returns the standard Parameter, Symbol, Value, Unit, Description columns.
% No speed/accuracy label is a measured runtime or uncertainty certificate.
methods = QuasiOpticalMethodCatalog;
records = { ...
    'Scope','','Free-space slab conversion','', ...
        'NRW: normal or oblique TE/TM; NIST and new non-iterative: normal only; homogeneous isotropic slab in air'; ...
    'Required data','','Calibrated complex reflection and transmission','', ...
        'Amplitude and phase, reference planes at sample surfaces, known normal thickness'; ...
    'Channel modes','','S11/S21 pair or S11/S21/S12/S22 four-channel projection','', ...
        'Four-channel mode assumes reciprocity and slab symmetry; raw reconstruction is checked'; ...
    'Four-channel reflection','r','(S11 + S22)/2','complex amplitude', ...
        'Symmetric reflection projection, applied only in selected four-channel mode'; ...
    'Four-channel transmission','t','(S21 + S12)/2','complex amplitude', ...
        'Reciprocal transmission projection, applied only in selected four-channel mode'; ...
    'Source','','Rohde & Schwarz, Measurement of Dielectric Material Properties, April 2012','', ...
        'Supplied RAC-0607-0019_1_5E.pdf; internal revision RAC0607-0019_1_4E'; ...
    'Comparison tables','','Tables 3 and 4; free-space rows only','pages 11, 16', ...
        'The combined NIST / new non-iterative free-space row is separated by method'; ...
    'Source material category','','High-temperature solids; large, flat; nonmagnetic','', ...
        'Category from source Table 4; software applies no temperature compensation'; ...
    'Meaning of speed and accuracy','','Qualitative source comparison','', ...
        'Not measured software performance, quantitative uncertainty, or an accuracy guarantee'; ...
    'SCL excluded','','Short-circuited coaxial / waveguide fixture','source page 15', ...
        'Not an unbacked free-space slab method; metal-backed free-space inversion needs a separate model'};
for k=1:numel(methods)
    method=methods(k); prefix=[method.name ' - '];
    sourcePages=strjoin(cellstr(string(method.sourcePages)),', ');
    records(end+1,:)={[prefix 'channels'],'',method.channels,'', ...
        'Pair mode or reciprocal symmetric four-channel projection'}; %#ok<AGROW>
    records(end+1,:)={[prefix 'outputs'],'',method.outputs,'relative', ...
        'Complex scalar properties; not general anisotropic tensor retrieval'}; %#ok<AGROW>
    records(end+1,:)={[prefix 'permeability'],'mu_r',method.muTreatment,'relative', ...
        'Assumed permeability is distinct from independently measured permeability'}; %#ok<AGROW>
    records(end+1,:)={[prefix 'incidence scope'],'',method.status,'', ...
        strjoin(method.assumptions,' | ')}; %#ok<AGROW>
    records(end+1,:)={[prefix 'source speed'],'',method.speed,'qualitative',method.accuracyMeaning}; %#ok<AGROW>
    records(end+1,:)={[prefix 'source accuracy'],'',method.accuracyQualitative,'qualitative',method.accuracyMeaning}; %#ok<AGROW>
    records(end+1,:)={[prefix 'source material'],'',method.material,'', ...
        'Source comparison category; independent model and calibration checks still apply'}; %#ok<AGROW>
    records(end+1,:)={[prefix 'advantages'],'',strjoin(method.advantages,' | '),'conditional', ...
        'Concise benefits under each implemented method incidence restriction'}; %#ok<AGROW>
    records(end+1,:)={[prefix 'disadvantages'],'',strjoin(method.disadvantages,' | '),'conditional', ...
        'Limitations remain dependent on sample, calibration, branch and numerical conditioning'}; %#ok<AGROW>
    records(end+1,:)={[prefix 'source pages'],'',sourcePages,'page', ...
        'Pages in the supplied application note'}; %#ok<AGROW>
end
params=cell2table(records,'VariableNames',{'Parameter','Symbol','Value','Unit','Description'});
for k=1:width(params)
    name=params.Properties.VariableNames{k}; params.(name)=string(params.(name));
end
end
